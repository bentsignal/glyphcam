fn draw_text(
    buf: &mut [u8],
    w: usize,
    h: usize,
    text: &str,
    cy: usize,
    scale: usize,
    color: [u8; 3],
) {
    let tw = text.chars().count() * 6 * scale;
    let x0 = w.saturating_sub(tw) / 2;
    for (i, c) in text.chars().enumerate() {
        let g = glyph(c);
        for (row, bits) in g.iter().enumerate() {
            for col in 0..5 {
                if bits & (0x10 >> col) == 0 {
                    continue;
                }
                for dy in 0..scale {
                    for dx in 0..scale {
                        let x = x0 + (i * 6 + col) * scale + dx;
                        let y = cy + row * scale + dy;
                        if x < w && y < h {
                            let o = (y * w + x) * 4;
                            buf[o] = color[2];
                            buf[o + 1] = color[1];
                            buf[o + 2] = color[0];
                        }
                    }
                }
            }
        }
    }
}

/// Render the placeholder for `state` as top-down BGRA.
pub fn render(state: WriterState, w: usize, h: usize) -> Vec<u8> {
    let mut buf = vec![0u8; w * h * 4];
    // dark backdrop with a faint dot grid
    for y in 0..h {
        for x in 0..w {
            let o = (y * w + x) * 4;
            let dot = (x % 24 == 12) && (y % 24 == 12);
            buf[o] = if dot { 40 } else { 6 };
            buf[o + 1] = if dot { 70 } else { 10 };
            buf[o + 2] = if dot { 30 } else { 4 };
            buf[o + 3] = 255;
        }
    }
    let unit = (h / 120).max(1);
    let (line1, line2) = match state {
        WriterState::Offline => (
            "GLYPHCAM IS NOT RUNNING",
            "OPEN GLYPHCAM TO START THE CAMERA",
        ),
        WriterState::Starting => ("STARTING CAMERA...", "ONE MOMENT"),
        WriterState::Paused => ("VIRTUAL CAMERA PAUSED", "TURN IT ON IN GLYPHCAM"),
        WriterState::NoCamera => ("NO CAMERA FOUND", "CHECK THE CAMERA IN GLYPHCAM SETTINGS"),
        WriterState::Live => ("", ""),
    };
    draw_text(
        &mut buf,
        w,
        h,
        "GLYPHCAM",
        h * 30 / 100,
        unit * 3,
        [40, 255, 90],
    );
    draw_text(&mut buf, w, h, line1, h * 55 / 100, unit, [200, 255, 210]);
    draw_text(
        &mut buf,
        w,
        h,
        line2,
        h * 55 / 100 + unit * 12,
        unit,
        [90, 160, 100],
    );
    buf
}
